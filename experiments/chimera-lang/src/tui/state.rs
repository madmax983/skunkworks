    pub fn next_view(&self) -> ViewMode {
        let views = crate::tui::get_all_views();
        let current_idx = views.iter().position(|(v, _, _)| v == self).unwrap_or(0);
        views[(current_idx + 1) % views.len()].0
    }

    /// Returns true if the grid is navigable in the current mode.
    pub fn is_grid_navigable(&self) -> bool {
        match self {
            ViewMode::Grid | ViewMode::BioticChaos => true,
            #[cfg(feature = "nova")]
            ViewMode::Kaleidoscope
            | ViewMode::Metazoa
            | ViewMode::Chronos
            | ViewMode::Logos
            | ViewMode::Void
            | ViewMode::Signals
            | ViewMode::Sovereignty
            | ViewMode::Spectrogram
            | ViewMode::Garden
            | ViewMode::Orca
            | ViewMode::Hydra
            | ViewMode::Hologram
            | ViewMode::Virology
            | ViewMode::BioMesh
            | ViewMode::Reactor
            | ViewMode::Biolum
            | ViewMode::Ecology => true,
            #[cfg(feature = "elektra")]
            ViewMode::Elektra => true,
            #[cfg(feature = "silicon")]
            ViewMode::Foundry => true,
            _ => false,
        }
    }
