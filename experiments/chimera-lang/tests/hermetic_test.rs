use chimera_lang::prelude::*;
use chimera_lang::prologue_compiler;
use chimera_lang::vm::{ChimeraVM, Value};

#[test]
fn test_hermetic_alchemy() {
    // 1. Define source with custom alchemy rules
    let source = r#"
        config {
            mode: Normal
        }
        grid {
            "A" "B" "C"
            "." "☿" "."
            "." "." "."
        }
        alchemy {
            "A" + "B" -> "Gold"
            "C" + "B" -> "Silver"
        }
        dna {
            strand main {
                nop
            }
        }
    "#;

    // 2. Compile
    let (dna, grid_opt, _, _, alchemy_book) =
        prologue_compiler::compile(source, None).expect("Compilation failed");

    // Verify book was parsed
    assert_eq!(alchemy_book.len(), 2);
    assert_eq!(alchemy_book[0].result, Value::Str("Gold".to_string()));

    // 3. Initialize VM
    let mut vm = ChimeraVM::new(dna);
    if let Some(grid) = grid_opt {
        vm.grid = grid;
    }
    vm.prologue_state.active = true;
    vm.prologue_state.alchemy_book = alchemy_book;

    // 4. Verify Initial State
    // (0,0)=A, (0,1)=B, (0,2)=C
    // (1,1)=Mercury(☿)
    assert_eq!(vm.grid[0][0], Value::Str("A".to_string()));
    assert_eq!(vm.grid[0][1], Value::Str("B".to_string()));
    assert_eq!(vm.grid[1][1], Value::Str("☿".to_string()));

    // 5. Execute Tick (Mercury reads neighbors)
    // Mercury at (1,1) reads N(0,1)="B", W(1,0)=".", E(1,2)=".", S(2,1)="."
    // Wait, Mercury reads neighbors.
    // Let's place ingredients adjacent to Mercury for the test.
    // Neighbors of (1,1) are (0,1), (2,1), (1,0), (1,2).
    // Let's update grid setup to ensure ingredients are adjacent.

    vm.grid[0][1] = Value::Str("A".to_string()); // North
    vm.grid[1][0] = Value::Str("B".to_string()); // West

    // Force signal update (normally happens in scan/prepare phase)
    vm.prologue_state.signal_grid[0][1] = Some(Value::Str("A".to_string()));
    vm.prologue_state.signal_grid[1][0] = Some(Value::Str("B".to_string()));

    // Run Prologue logic manually or via tick
    // We can call apply_elemental_runes directly or run full tick.
    // Full tick is safer integration test.

    // Note: exec_prologue_tick scans grid, prepares signals (if ! source), propagates.
    // Static values don't emit signals unless they are sources or we use `!` adjacent.
    // But `☿` reads from *signals*.
    // So we need `!` sources or pre-filled signal grid.

    // Let's use `!` sources in the grid setup.
    // Grid:
    // "A" "!" "."
    // "B" "☿" "."
    // "!" "." "."

    // (0,0)="A", (0,1)="!" -> Emits "A" to (0,1) signals? No, ! reads West.
    // Let's use the explicit signal injection approach for the test as it's cleaner than relying on tick timing.

    // Re-setup signals explicitly
    vm.prologue_state.signal_grid[0][1] = Some(Value::Str("A".to_string())); // North of Mercury
    vm.prologue_state.signal_grid[1][0] = Some(Value::Str("B".to_string())); // West of Mercury

    // We need to pass the alchemy book to the function, but it's part of VM state now?
    // In `apply_elemental_runes`, we passed `&vm.prologue_state.alchemy_book`.
    // But `exec_prologue_tick` calls it.

    chimera_lang::vm::prologue::exec_prologue_tick(&mut vm);

    // 6. Verify Result
    // Mercury at (1,1) should have transmuted to "Gold"
    // Next signals should have "Gold" at (1,1)
    // And logic might write it to grid?
    // `apply_elemental_runes` writes to `next_signals`.
    // `process_signal_propagation` swaps buffers.
    // It doesn't write to grid directly unless a Sink consumes it or it's a specific rune.
    // Mercury outputs to Self. So `signal_grid[1][1]` should be "Gold".

    // Note: `exec_prologue_tick` clears `signal_grid` at start of tick (`prepare_signals`).
    // So if we inject signals *before* calling it, they get wiped unless they are in `delayed_signals` or generated by sources.

    // Let's use the delayed signals injection which persists to next tick.
    vm.prologue_state.delayed_signals[0][1] = Some(Value::Str("A".to_string()));
    vm.prologue_state.delayed_signals[1][0] = Some(Value::Str("B".to_string()));

    chimera_lang::vm::prologue::exec_prologue_tick(&mut vm);

    if let Some(val) = &vm.prologue_state.signal_grid[1][1] {
        assert_eq!(*val, Value::Str("Gold".to_string()));
    } else {
        panic!(
            "Mercury failed to transmute signals. Signals: {:?}",
            vm.prologue_state.signal_grid
        );
    }
}
