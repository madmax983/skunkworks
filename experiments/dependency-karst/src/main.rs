//! # Dependency Karst ⚛️🪨
//!
//! > "The codebase is a solid block of potential. Dependencies are the acid that carves the void." — Genesis (The Geologist)
//!
//! **Dependency Karst** is a geological simulation of your dependency graph. It maps your `cargo` dependencies to a 3D voxel grid and simulates "acid erosion" along the dependency paths.
//!
//! *   **Rock**: The solid void of unlinked code.
//! *   **Acid**: Dependency usage flowing from crate to crate.
//! *   **Caves**: The resulting tunnels carved by the dependency graph.
//! *   **Fault Lines**: Initial Perlin noise weaknesses in the rock that guide the flow.
//!
//! ## 🎮 Controls
//!
//! | Key | Action |
//! | :--- | :--- |
//! | **`W` / `A` / `S` / `D`** | Move Cursor (X/Y) |
//! | **`E`** / **`PageUp`** | Move Slice Up (Z+) |
//! | **`Q`** / **`PageDown`** | Move Slice Down (Z-) |
//! | **`R`** / **`Enter`** | **Run Erosion Step** (Watch the caves grow!) |
//! | **`Esc`** | Exit |
//!
//! ## 🧪 The Science
//!
//! 1.  **Embedding**: Crates are mapped to a 3D grid using a force-directed layout.
//! 2.  **Geology**: The grid starts as solid rock, with random "fault lines" generated by 3D Perlin noise.
//! 3.  **Hydrology**: "Acid" agents spawn at dependency sources and flow towards their targets.
//! 4.  **Erosion**: As agents move, they dissolve the rock into air. They prefer following existing fault lines, creating organic, cave-like structures rather than straight lines.
//!
//! ## 📦 Usage
//!
//! ```bash
//! cargo run -p dependency-karst
//! ```
//!
//! Navigate the slices to see the internal structure of your dependency graph!
//!
use anyhow::Result;
use crossterm::event::{self, Event, KeyCode, KeyEventKind};
use dependency_karst::load_graph;
use dependency_karst::Layout;
use dependency_karst::{CaveWidget, TuiState};
use dependency_karst::{VoxelGrid, GRID_SIZE};
use tui_shared::Tui;

fn main() -> Result<()> {
    // Setup Terminal
    let mut tui = Tui::init()?;

    // Load Data
    let graph = load_graph()?;
    let mut layout = Layout::new(&graph);
    // Optimize layout a bit more
    layout.optimize(&graph, 200);

    // Init Simulation
    let mut grid = VoxelGrid::new();
    let mut state = TuiState::new();

    // App Loop
    let mut running = true;
    while running {
        tui.terminal.draw(|f| {
            let size = f.area();
            let widget = CaveWidget::new(&grid, &state, &layout.positions, &graph);
            f.render_widget(widget, size);
        })?;

        if event::poll(std::time::Duration::from_millis(50))? {
            if let Event::Key(key) = event::read()? {
                if key.kind == KeyEventKind::Press {
                    match key.code {
                        KeyCode::Esc => running = false,
                        KeyCode::Char('w') | KeyCode::Up => {
                            if state.cursor_y > 0 {
                                state.cursor_y -= 1;
                            }
                        }
                        KeyCode::Char('s') | KeyCode::Down => {
                            if state.cursor_y < GRID_SIZE - 1 {
                                state.cursor_y += 1;
                            }
                        }
                        KeyCode::Char('a') | KeyCode::Left => {
                            if state.cursor_x > 0 {
                                state.cursor_x -= 1;
                            }
                        }
                        KeyCode::Char('d') | KeyCode::Right => {
                            if state.cursor_x < GRID_SIZE - 1 {
                                state.cursor_x += 1;
                            }
                        }
                        KeyCode::Char('e') | KeyCode::PageUp => {
                            if state.slice_z < GRID_SIZE - 1 {
                                state.slice_z += 1;
                            }
                        }
                        KeyCode::Char('q') | KeyCode::PageDown => {
                            if state.slice_z > 0 {
                                state.slice_z -= 1;
                            }
                        }
                        KeyCode::Char('r') | KeyCode::Enter => {
                            // Run erosion step
                            grid.erode(&graph, &layout.positions);
                        }
                        _ => {}
                    }
                }
            }
        }
    }

    Ok(())
}
