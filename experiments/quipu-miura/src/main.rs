//! # Quipu Miura 🗺️🧶
//!
//! Resurrection cross: `quipu-origami` (graveyard) × `origami`
//! (living), brought by The Cartographer of Lost Things 🗺️.
//!
//! The dead specimen's idea was sound — knotted data should fold
//! paper — but its body was not: it drew flat dots wobbled by a sine
//! wave and called that morphogenesis. The Reaper's report names the
//! flaw exactly: no genuine bidirectional interaction, no true 3D
//! Miura-ori mesh, the cords barely influencing the outcome.
//!
//! Here the donation is real. Every decimal digit of every quipu
//! cord becomes one vertical strip of a genuine Miura-ori sheet,
//! generated by the living `origami` crate's `generate_miura_mesh`
//! (real vertices, real indices, real 3D heights). A digit sets its
//! strip's target extension and its stiffness — more knots, stiffer
//! cord. Then the paper negotiates: adjacent strips must meet at a
//! seam, and mismatched fold heights pull neighbouring extensions
//! toward each other while each strip's knots spring it back toward
//! its tied target. The equilibrium is neither the cord's dictation
//! nor the paper's preference; it is what both survived.
//!
//! Finally the folded sheet is read back: each strip's settled
//! extension is decoded to a digit, the digits are re-tied into
//! cords, and the readback ledger is compared against the original
//! quipu folded with `checked_add`. What the seams cost the ledger
//! is printed, not hidden.

use anyhow::Result;
use origami::{generate_miura_mesh, MiuraParams, Orientation, OrigamiMesh};
use quipu::{Cord, Quipu};

/// Miura cells per strip (cols, rows).
const STRIP_CELLS: (usize, usize) = (4, 6);
/// Extension a digit of 0 asks for (a quipu zero is an empty space:
/// the strip stays nearly flat, but present).
const EXT_MIN: f32 = 0.12;
/// Extension a digit of 9 asks for.
const EXT_MAX: f32 = 0.95;
/// Relaxation stops when seam energy falls below this, or after
/// MAX_STEPS iterations.
const ENERGY_EPSILON: f32 = 1e-5;
const MAX_STEPS: usize = 400;

/// One strip of the sheet: one decimal digit of one cord.
/// Crease angle every strip is tied with, before the paper objects.
const GAMMA_TIED: f32 = 1.2;
/// The paper may re-crease within these bounds while negotiating.
const GAMMA_MIN: f32 = 0.85;
const GAMMA_MAX: f32 = 1.50;

#[derive(Debug, Clone)]
struct Strip {
    cord_index: usize,
    digit: u8,
    target: f32,
    extension: f32,
    /// This strip's crease angle — the paper's own degree of
    /// freedom, the one the knots do not dictate.
    gamma: f32,
}

impl Strip {
    fn target_for(digit: u8) -> f32 {
        EXT_MIN + (digit as f32 / 9.0) * (EXT_MAX - EXT_MIN)
    }
    /// More knots, stiffer cord: 0.30 (empty space) .. 0.93 (nine).
    fn stiffness(&self) -> f32 {
        0.30 + 0.07 * self.digit as f32
    }
    fn mesh(&self) -> OrigamiMesh {
        let params = MiuraParams {
            a: 1.0,
            b: 1.0,
            gamma: self.gamma,
            orientation: Orientation::Horizontal,
        };
        generate_miura_mesh(params, STRIP_CELLS, self.extension)
    }
}

/// Decimal digits of a cord's value, most significant first — the
/// positional places the quipu itself ties (hundreds, tens, units).
fn digits_of(value: u64) -> Vec<u8> {
    if value == 0 {
        return vec![0];
    }
    let mut digits = Vec::new();
    let mut v = value;
    while v > 0 {
        digits.push((v % 10) as u8);
        v /= 10;
    }
    digits.reverse();
    digits
}

/// Fold profile along one vertical edge of a mesh: each edge
/// vertex's 3D position relative to the edge's first vertex.
/// (Surveyor's note: in this crate's Horizontal Miura, edge *z*
/// alone is identically zero at even columns — the seam mismatch
/// lives in the row spacing and the zig-zag x-offset, which vary
/// with extension. A z-only survey reads a flat map of folded land.)
fn edge_profile(mesh: &OrigamiMesh, right: bool) -> Vec<(f32, f32, f32)> {
    let v_cols = STRIP_CELLS.0 + 1;
    let rows = STRIP_CELLS.1;
    let col = if right { STRIP_CELLS.0 } else { 0 };
    let origin = mesh.vertices[col].pos;
    (0..=rows)
        .map(|j| {
            let p = mesh.vertices[j * v_cols + col].pos;
            (p.x - origin.x, p.y - origin.y, p.z - origin.z)
        })
        .collect()
}

/// Total seam energy: sum over adjacent strip pairs of the squared
/// 3D profile mismatch along their shared edge. Zero would mean the
/// strips meet as one continuous sheet.
fn seam_energy(strips: &[Strip]) -> f32 {
    let meshes: Vec<OrigamiMesh> = strips.iter().map(|s| s.mesh()).collect();
    let mut energy = 0.0f32;
    for pair in meshes.windows(2) {
        let left_edge = edge_profile(&pair[0], true);
        let right_edge = edge_profile(&pair[1], false);
        for (a, b) in left_edge.iter().zip(right_edge.iter()) {
            energy += (a.0 - b.0) * (a.0 - b.0)
                + (a.1 - b.1) * (a.1 - b.1)
                + (a.2 - b.2) * (a.2 - b.2);
        }
    }
    energy
}

/// 3D surface area of a mesh from its own indices — proof the sheet
/// is a folded surface, not a projection.
fn surface_area(mesh: &OrigamiMesh) -> f32 {
    let mut area = 0.0f32;
    for tri in mesh.indices.chunks_exact(3) {
        let a = mesh.vertices[tri[0] as usize].pos;
        let b = mesh.vertices[tri[1] as usize].pos;
        let c = mesh.vertices[tri[2] as usize].pos;
        let (ux, uy, uz) = (b.x - a.x, b.y - a.y, b.z - a.z);
        let (vx, vy, vz) = (c.x - a.x, c.y - a.y, c.z - a.z);
        let (cx, cy, cz) = (uy * vz - uz * vy, uz * vx - ux * vz, ux * vy - uy * vx);
        area += 0.5 * (cx * cx + cy * cy + cz * cz).sqrt();
    }
    area
}

#[derive(Debug)]
struct Ledger {
    cords: usize,
    quipu_total: u64,
    strips: usize,
    vertices: usize,
    triangles: usize,
    surface_area: f32,
    height_range: f32,
    initial_seam_energy: f32,
    final_seam_energy: f32,
    relax_steps: usize,
    max_deviation: f32,
    max_gamma_shift: f32,
    digits_preserved: usize,
    readback_total: u64,
    readback_cords: Vec<u64>,
}

/// Fold a quipu from raw values, lay its digits out as strips,
/// relax the seams, and read the sheet back.
fn run(values: &[u64]) -> Result<(Quipu, Vec<Strip>, Ledger)> {
    let mut quipu = Quipu::new();
    for &v in values {
        quipu.add_cord(Cord::from(v));
    }
    let quipu_total = quipu
        .cords
        .iter()
        .fold(Cord::from(0u64), |acc, c| acc.checked_add(c).expect("ledger overflow"))
        .value();

    let mut strips: Vec<Strip> = Vec::new();
    for (ci, &v) in values.iter().enumerate() {
        for d in digits_of(v) {
            strips.push(Strip {
                cord_index: ci,
                digit: d,
                target: Strip::target_for(d),
                extension: Strip::target_for(d),
                gamma: GAMMA_TIED,
            });
        }
    }

    let initial_seam_energy = seam_energy(&strips);

    // The negotiation. Two degrees of freedom, two owners:
    //  - extension is the knots': seams pull a strip toward its
    //    neighbours' extensions (less if the strip is stiff with
    //    knots), and the knots spring it back toward its target.
    //  - gamma (crease angle) is the paper's: each strip re-creases
    //    by hill-climbing its own local seam energy, absorbing
    //    mismatch the ledger refuses to pay for.
    // No clock, no sine: the only driver is geometric mismatch.
    let local_energy = |strips: &[Strip], i: usize| -> f32 {
        let mut e = 0.0f32;
        for (a, b) in [(i.wrapping_sub(1), i), (i, i + 1)] {
            if a < strips.len() && b < strips.len() && a != b {
                let left = edge_profile(&strips[a].mesh(), true);
                let right = edge_profile(&strips[b].mesh(), false);
                for (p, q) in left.iter().zip(right.iter()) {
                    e += (p.0 - q.0) * (p.0 - q.0)
                        + (p.1 - q.1) * (p.1 - q.1)
                        + (p.2 - q.2) * (p.2 - q.2);
                }
            }
        }
        e
    };
    let mut steps = 0usize;
    let mut energy = initial_seam_energy;
    while energy > ENERGY_EPSILON && steps < MAX_STEPS {
        // Paper's move: re-crease each strip toward quieter seams.
        for i in 0..strips.len() {
            let here = local_energy(&strips, i);
            for delta in [0.02f32, -0.02] {
                let trial = (strips[i].gamma + delta).clamp(GAMMA_MIN, GAMMA_MAX);
                if trial == strips[i].gamma {
                    continue;
                }
                let saved = strips[i].gamma;
                strips[i].gamma = trial;
                if local_energy(&strips, i) < here {
                    break;
                }
                strips[i].gamma = saved;
            }
        }
        // Knots' move: extension negotiation under spring tension.
        let current: Vec<f32> = strips.iter().map(|s| s.extension).collect();
        for i in 0..strips.len() {
            let mut neighbours = Vec::new();
            if i > 0 {
                neighbours.push(current[i - 1]);
            }
            if i + 1 < current.len() {
                neighbours.push(current[i + 1]);
            }
            if neighbours.is_empty() {
                continue;
            }
            let neighbour_mean =
                neighbours.iter().sum::<f32>() / neighbours.len() as f32;
            let seam_pull =
                0.06 * (neighbour_mean - current[i]) * (1.0 - 0.5 * strips[i].stiffness());
            let knot_spring = 0.60 * (strips[i].target - current[i]);
            strips[i].extension =
                (current[i] + seam_pull + knot_spring).clamp(0.02, 0.99);
        }
        steps += 1;
        energy = seam_energy(&strips);
    }
    let final_seam_energy = energy;

    // Census of the settled sheet, from its own geometry.
    let mut vertices = 0usize;
    let mut triangles = 0usize;
    let mut area = 0.0f32;
    let mut z_min = f32::INFINITY;
    let mut z_max = f32::NEG_INFINITY;
    for s in &strips {
        let mesh = s.mesh();
        vertices += mesh.vertices.len();
        triangles += mesh.indices.len() / 3;
        area += surface_area(&mesh);
        for v in &mesh.vertices {
            z_min = z_min.min(v.pos.z);
            z_max = z_max.max(v.pos.z);
        }
    }

    // Readback: decode each settled extension to the nearest digit
    // and re-tie the cords.
    let mut digits_preserved = 0usize;
    let mut readback_cords = vec![0u64; values.len()];
    for s in &strips {
        let decoded = (((s.extension - EXT_MIN) / (EXT_MAX - EXT_MIN)) * 9.0)
            .round()
            .clamp(0.0, 9.0) as u8;
        if decoded == s.digit {
            digits_preserved += 1;
        }
        readback_cords[s.cord_index] = readback_cords[s.cord_index] * 10 + decoded as u64;
    }
    let readback_total: u64 = readback_cords.iter().sum();
    let max_deviation = strips
        .iter()
        .map(|s| (s.extension - s.target).abs())
        .fold(0.0f32, f32::max);
    let max_gamma_shift = strips
        .iter()
        .map(|s| (s.gamma - GAMMA_TIED).abs())
        .fold(0.0f32, f32::max);

    Ok((
        quipu,
        strips.clone(),
        Ledger {
            cords: values.len(),
            quipu_total,
            strips: strips.len(),
            vertices,
            triangles,
            surface_area: area,
            height_range: z_max - z_min,
            initial_seam_energy,
            final_seam_energy,
            relax_steps: steps,
            max_deviation,
            max_gamma_shift,
            digits_preserved,
            readback_total,
            readback_cords,
        },
    ))
}

/// The demo ledger: five cords whose digits disagree with their
/// neighbours loudly enough that the paper has something to say.
fn demo_values() -> Vec<u64> {
    vec![420, 77, 108, 9, 1234]
}

fn print_ledger(values: &[u64], ledger: &Ledger) {
    println!("quipu-miura headless: the grave at graveyard/quipu-origami, re-folded");
    println!("  cords tied:              {}", ledger.cords);
    println!("  quipu total (checked_add): {}", ledger.quipu_total);
    println!("  digit strips laid:       {}", ledger.strips);
    println!("  mesh vertices (real 3D): {}", ledger.vertices);
    println!("  mesh triangles:          {}", ledger.triangles);
    println!("  surface area:            {:.2}", ledger.surface_area);
    println!("  fold height range:       {:.3}", ledger.height_range);
    println!("  seam energy, at tying:   {:.4}", ledger.initial_seam_energy);
    println!("  seam energy, settled:    {:.6}", ledger.final_seam_energy);
    println!("  relaxation steps:        {}", ledger.relax_steps);
    println!("  max deviation from knot target: {:.4}", ledger.max_deviation);
    println!("  max crease re-cut (gamma shift): {:.3} rad", ledger.max_gamma_shift);
    println!("  digits preserved:        {}/{}", ledger.digits_preserved, ledger.strips);
    println!("  readback cords:          {:?}", ledger.readback_cords);
    println!("  readback total:          {} (original {})", ledger.readback_total, ledger.quipu_total);
    println!("  original cords:          {:?}", values);
}

fn main() -> Result<()> {
    let args: Vec<String> = std::env::args().collect();
    // Headless is decided before anything else is built — there is
    // no TUI or window in this specimen at all, and there never will
    // be one standing between the ledger and CI.
    let headless = args.iter().any(|a| a == "--headless");
    let values: Vec<u64> = args
        .iter()
        .skip(1)
        .filter(|a| !a.starts_with("--"))
        .filter_map(|a| a.parse::<u64>().ok())
        .collect();
    let values = if values.is_empty() { demo_values() } else { values };
    let (_quipu, _strips, ledger) = run(&values)?;
    print_ledger(&values, &ledger);
    if !headless {
        println!("  (fold it headless any time: --headless [cord values...])");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_sheet_is_a_real_folded_surface() {
        let (_, strips, ledger) = run(&demo_values()).unwrap();
        // Every strip is a genuine Miura mesh from the origami
        // crate: (cols+1)*(rows+1) vertices, cols*rows*2 triangles.
        assert_eq!(ledger.vertices, strips.len() * (STRIP_CELLS.0 + 1) * (STRIP_CELLS.1 + 1));
        assert_eq!(ledger.triangles, strips.len() * STRIP_CELLS.0 * STRIP_CELLS.1 * 2);
        // A flat dot projection has no height and no folded area.
        assert!(ledger.height_range > 0.1, "sheet is flat: {}", ledger.height_range);
        assert!(ledger.surface_area > 10.0, "no folded surface: {}", ledger.surface_area);
    }

    #[test]
    fn seams_relax_under_negotiation() {
        let (_, _, ledger) = run(&demo_values()).unwrap();
        assert!(ledger.initial_seam_energy > 0.01, "nothing to negotiate: {}", ledger.initial_seam_energy);
        assert!(
            ledger.final_seam_energy < ledger.initial_seam_energy * 0.5,
            "seam energy barely moved: {} -> {}",
            ledger.initial_seam_energy, ledger.final_seam_energy
        );
        assert!(ledger.relax_steps > 1);
        // The paper did some of the work itself: at least one strip
        // re-creased rather than forcing the knots to pay it all.
        assert!(ledger.max_gamma_shift > 0.01, "no strip re-creased: {}", ledger.max_gamma_shift);
    }

    #[test]
    fn the_paper_pushes_back_and_stiff_knots_push_harder() {
        // The dead specimen's cords barely influenced the outcome,
        // and nothing influenced the cords. Here the seam must move
        // at least one strip off its tied target...
        let (_, _, ledger) = run(&demo_values()).unwrap();
        assert!(ledger.max_deviation > 0.005, "paper never pushed back: {}", ledger.max_deviation);
        // ...and in a two-strip sheet [9, 0], the slack strip (the
        // quipu zero, an empty space) must yield further than the
        // stiff nine-knot strip.
        let (_, strips, _) = run(&[90]).unwrap();
        let dev_stiff = (strips[0].extension - strips[0].target).abs();
        let dev_slack = (strips[1].extension - strips[1].target).abs();
        assert!(dev_slack > dev_stiff, "slack yielded {dev_slack}, stiff yielded {dev_stiff}");
        assert!(dev_slack > 0.01, "slack strip did not yield: {dev_slack}");
    }

    #[test]
    fn readback_recovers_most_of_the_ledger() {
        let (_, _, ledger) = run(&demo_values()).unwrap();
        // The seams are allowed their toll, but a resurrection that
        // loses the ledger has only traded one death for another.
        assert!(
            ledger.digits_preserved * 4 >= ledger.strips * 3,
            "only {}/{} digits survived the folding",
            ledger.digits_preserved, ledger.strips
        );
        let drift = ledger.readback_total.abs_diff(ledger.quipu_total);
        assert!(drift <= ledger.quipu_total / 4, "readback drifted {drift} from {}", ledger.quipu_total);
    }

    #[test]
    fn different_cords_fold_different_sheets() {
        let (_, _, a) = run(&[420, 77]).unwrap();
        let (_, _, b) = run(&[421, 77]).unwrap();
        assert_ne!(a.initial_seam_energy, b.initial_seam_energy);
        assert_ne!(a.surface_area, b.surface_area);
    }
}
