//! # Market Simulation & Algorithmic Trading 📊
//!
//! This module simulates a volatile market and an automated trader that uses
//! a **Soroban** (Abacus) to compute technical indicators.
//!
//! ## The Model
//! * **Market**: A random walk process representing asset price history.
//! * **Trader**: A bot that calculates the **Simple Moving Average (SMA)**.
//!
//! The unique twist is that the `Trader` uses a physical `Soroban` struct
//! to maintain the running sum of prices, adding new prices and subtracting old ones
//! bead-by-bead.

use rand::Rng;
use soroban::Soroban;

/// Trading signals generated by the bot.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Signal {
    /// Price is significantly above SMA (Momentum Buy).
    Buy,
    /// Price is significantly below SMA (Momentum Sell).
    Sell,
    /// Price is near SMA.
    Hold,
}

/// Represents the continuous market environment.
///
/// The market evolves via a random walk process.
pub struct Market {
    /// History of all price points.
    /// Prices are stored as integers (e.g., 10000 = $100.00) to avoid floating point errors
    /// on the Soroban.
    pub prices: Vec<u64>,
    /// The most recent price.
    pub current_price: u64,
}

impl Default for Market {
    fn default() -> Self {
        Self {
            prices: vec![10000], // Start at 100.00
            current_price: 10000,
        }
    }
}

impl Market {
    /// Creates a new market starting at price 100.00.
    pub fn new() -> Self {
        Self::default()
    }

    /// Advances the market by one time step.
    ///
    /// The price changes by a random amount in the range [-0.50, +0.50].
    /// The price is clamped to be at least 0.01 (1).
    pub fn update(&mut self) {
        let mut rng = rand::thread_rng();
        let change: i64 = rng.gen_range(-50..51); // -0.50 to +0.50 change

        // Random walk with drift? No, pure random walk.
        let new_price = (self.current_price as i64 + change).max(1) as u64;
        self.prices.push(new_price);
        self.current_price = new_price;
    }
}

/// An algorithmic trader that uses a Soroban for calculations.
///
/// The trader maintains a **Simple Moving Average (SMA)** of the price history.
/// Instead of recalculating the sum every frame, it maintains a **Running Sum**
/// on the Soroban:
///
/// 1.  Add the new price to the Soroban.
/// 2.  Subtract the old price (exiting the window) from the Soroban.
/// 3.  The value on the Soroban is the sum of the current window.
pub struct Trader {
    /// The abacus used for the running sum.
    pub soroban: Soroban,
    /// The size of the moving average window (N).
    pub window_size: usize,
    /// The current calculated SMA.
    pub current_sma: u64,
    /// The most recent trading signal.
    pub last_signal: Signal,
}

impl Trader {
    /// Creates a new trader with a specific SMA window size.
    pub fn new(window_size: usize) -> Self {
        Self {
            soroban: Soroban::new(),
            window_size,
            current_sma: 0,
            last_signal: Signal::Hold,
        }
    }

    /// Processes the latest market data and updates the strategy.
    ///
    /// * Updates the running sum on the Soroban.
    /// * Calculates the new SMA.
    /// * Generates a Buy/Sell signal if the price deviates from the SMA by > 0.10.
    pub fn process(&mut self, market: &Market) {
        let prices = &market.prices;
        let n = prices.len();

        if n < 1 {
            return;
        }

        let new_price = prices[n - 1];

        // Update Running Sum on Soroban
        self.soroban.add(new_price);

        if n > self.window_size {
            let old_price = prices[n - 1 - self.window_size];
            self.soroban.sub(old_price);
        }

        // Calculate SMA from Soroban value
        let sum = self.soroban.value();
        // Avoid division by zero
        let divisor = self.window_size.min(n) as u64;
        if divisor > 0 {
            self.current_sma = sum / divisor;
        }

        // Generate Signal
        if new_price > self.current_sma + 10 {
            self.last_signal = Signal::Buy;
        } else if new_price < self.current_sma.saturating_sub(10) {
            self.last_signal = Signal::Sell;
        } else {
            self.last_signal = Signal::Hold;
        }
    }
}
