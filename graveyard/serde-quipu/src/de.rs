use crate::error::Error;
use crate::quipu::{Cluster, Cord, Knot, Quipu};
use nom::{
    bytes::complete::{tag, take_until, take_while1},
    character::complete::{multispace0, newline, space0},
    combinator::opt,
    multi::many0,
    sequence::delimited,
    IResult,
};
use serde::de::{self, Deserialize, MapAccess, SeqAccess, Visitor};

pub fn from_str<'a, T: Deserialize<'a>>(s: &'a str) -> Result<T, Error> {
    let (_, quipu) = parse_quipu(s).map_err(|e| Error::Parse(e.to_string()))?;

    // The parsing returns a Quipu with a list of root cords.
    // Usually serialize produces a single root cord inside Quipu.
    // But our serialization produces "Q-ROOT" then "+-- RootCord".
    // So we should take the first cord.

    if let Some(root) = quipu.cords.first() {
        let deserializer = CordDeserializer { cord: root.clone() };
        T::deserialize(deserializer)
    } else {
        Err(Error::Parse("Empty Quipu".to_string()))
    }
}

// --- Parsing Logic ---

fn parse_quipu(input: &str) -> IResult<&str, Quipu> {
    let (input, _) = tag("Q-ROOT")(input)?;
    let (input, _) = multispace0(input)?;
    let (input, _) = tag("|")(input)?;
    let (input, _) = multispace0(input)?;

    // Parse lines. We need to handle indentation to reconstruct tree.
    // This is tricky with pure combinators.
    // Let's parse a flat list of (indent, CordData) and then reconstruct.

    let (input, lines) = many0(parse_line)(input)?;

    // Reconstruct tree
    let cords = reconstruct_tree(lines);

    Ok((input, Quipu { cords }))
}

struct LineData {
    indent: usize,
    color: String,
    clusters: Vec<Cluster>,
}

fn parse_line(input: &str) -> IResult<&str, LineData> {
    let (input, spaces) = space0(input)?;
    let indent = spaces.len();
    let (input, _) = tag("+-- ")(input)?;

    // Parse [Color]
    let (input, color) = delimited(tag("["), take_until("]"), tag("] "))(input)?;

    // Parse Knots
    // s-ss-L3
    // or (empty)

    let (input, knot_str) = take_while1(|c: char| c != '\n')(input)?;
    // Consume the newline that stopped take_while1, but NOT subsequent spaces of next line.
    // However, take_while1 doesn't consume the newline.
    // multispace0 consumes \n and subsequent spaces.
    // We should just consume \n (and \r if windows).
    // nom::character::complete::newline matches \n.
    // But if we are at EOF, newline might fail?
    // Let's use multispace0 BUT we know we are at end of line.
    // The problem is that multispace0 eats the indentation of the next line.

    // Better: Consume newline explicitly.
    let (input, _) = opt(newline)(input)?;

    // Parse knot_str into clusters
    let clusters = parse_knot_string(knot_str);

    Ok((
        input,
        LineData {
            indent,
            color: color.to_string(),
            clusters,
        },
    ))
}

fn parse_knot_string(s: &str) -> Vec<Cluster> {
    if s == "(empty)" {
        return Vec::new();
    }

    let parts: Vec<&str> = s.split('-').collect();
    let mut clusters = Vec::new();

    // We assume the string is generated by us: Highest power first.
    // So reverse index = power.
    let len = parts.len();

    for (i, part) in parts.iter().enumerate() {
        let power = (len - 1 - i) as u32;
        let mut knots = Vec::new();
        let mut value = 0;

        if *part == "_" {
            // zero
        } else {
            // Parse part: "sss", "L3", "E"
            if let Some(stripped) = part.strip_prefix("L") {
                if let Ok(v) = stripped.parse::<u8>() {
                    knots.push(Knot::Long(v));
                    value = v;
                }
            } else if *part == "E" {
                knots.push(Knot::FigureEight);
                value = 1;
            } else if part.chars().all(|c| c == 's') {
                let count = part.len() as u8;
                for _ in 0..count {
                    knots.push(Knot::Single);
                }
                value = count;
            }
        }

        clusters.push(Cluster {
            knots,
            value,
            position_power: power,
        });
    }

    clusters
}

fn reconstruct_tree(lines: Vec<LineData>) -> Vec<Cord> {
    // Stack-based reconstruction
    // Stack holds (indent, Cord)
    // When we see a line:
    //   while stack.top.indent >= current.indent: pop and add to new_top
    //   push new cord

    // But we need to return roots.
    // Let's assume root indent is 0 (relative to "+--").
    // Wait, parse_line returns indent of spaces BEFORE "+--".
    // Root usually has 0 spaces.

    let mut stack: Vec<(usize, Cord)> = Vec::new();
    let mut roots = Vec::new();

    for line in lines {
        let cord = Cord {
            clusters: line.clusters,
            color: line.color,
            subsidiaries: Vec::new(),
        };

        while let Some((last_indent, _)) = stack.last() {
            if *last_indent >= line.indent {
                let (_, popped_cord) = stack.pop().unwrap();
                if let Some((_, parent)) = stack.last_mut() {
                    parent.add_subsidiary(popped_cord);
                } else {
                    roots.push(popped_cord);
                }
            } else {
                break;
            }
        }

        stack.push((line.indent, cord));
    }

    // Flush stack
    while let Some((_, popped_cord)) = stack.pop() {
        if let Some((_, parent)) = stack.last_mut() {
            parent.add_subsidiary(popped_cord);
        } else {
            roots.push(popped_cord);
        }
    }

    roots
}

// --- Deserializer ---

struct CordDeserializer {
    cord: Cord,
}

impl<'de> de::Deserializer<'de> for CordDeserializer {
    type Error = Error;

    fn deserialize_any<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        // Guess type based on content?
        // If subsidiaries exist -> Map/Struct
        // If clusters exist -> Int/String
        if !self.cord.subsidiaries.is_empty() {
            self.deserialize_map(visitor)
        } else {
            self.deserialize_u64(visitor)
        }
    }

    fn deserialize_u64<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        visitor.visit_u64(self.cord.to_u64())
    }

    fn deserialize_bool<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        visitor.visit_bool(self.cord.to_u64() != 0)
    }

    fn deserialize_char<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        // Assuming u64
        if let Some(c) = std::char::from_u32(self.cord.to_u64() as u32) {
            visitor.visit_char(c)
        } else {
            Err(Error::Message("Invalid char".to_string()))
        }
    }

    fn deserialize_str<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        if !self.cord.subsidiaries.is_empty() {
            let mut s = String::new();
            for sub in &self.cord.subsidiaries {
                let c = std::char::from_u32(sub.to_u64() as u32)
                    .ok_or(Error::Message("Invalid char".to_string()))?;
                s.push(c);
            }
            visitor.visit_string(s)
        } else {
            visitor.visit_string(self.cord.color)
        }
    }

    fn deserialize_string<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        self.deserialize_str(visitor)
    }

    // Forward integers
    fn deserialize_i8<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        visitor.visit_i8(self.cord.to_u64() as i8)
    }
    fn deserialize_i16<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        visitor.visit_i16(self.cord.to_u64() as i16)
    }
    fn deserialize_i32<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        visitor.visit_i32(self.cord.to_u64() as i32)
    }
    fn deserialize_i64<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        visitor.visit_i64(self.cord.to_u64() as i64)
    }
    fn deserialize_u8<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        visitor.visit_u8(self.cord.to_u64() as u8)
    }
    fn deserialize_u16<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        visitor.visit_u16(self.cord.to_u64() as u16)
    }
    fn deserialize_u32<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        visitor.visit_u32(self.cord.to_u64() as u32)
    }
    fn deserialize_f32<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        visitor.visit_f32(self.cord.to_u64() as f32)
    }
    fn deserialize_f64<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        visitor.visit_f64(self.cord.to_u64() as f64)
    }

    fn deserialize_struct<V>(
        self,
        _name: &'static str,
        _fields: &'static [&'static str],
        visitor: V,
    ) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        self.deserialize_map(visitor)
    }

    fn deserialize_map<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        visitor.visit_map(CordMapAccess::new(self.cord.subsidiaries))
    }

    fn deserialize_seq<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        visitor.visit_seq(CordSeqAccess::new(self.cord.subsidiaries))
    }

    // Boilerplate for others
    fn deserialize_option<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        if self.cord.color == "None" {
            visitor.visit_none()
        } else {
            visitor.visit_some(self)
        }
    }

    fn deserialize_unit<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        visitor.visit_unit()
    }

    fn deserialize_unit_struct<V>(
        self,
        _name: &'static str,
        visitor: V,
    ) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        visitor.visit_unit()
    }

    fn deserialize_newtype_struct<V>(
        self,
        _name: &'static str,
        visitor: V,
    ) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        visitor.visit_newtype_struct(self)
    }

    fn deserialize_tuple<V>(self, _len: usize, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        self.deserialize_seq(visitor)
    }

    fn deserialize_tuple_struct<V>(
        self,
        _name: &'static str,
        _len: usize,
        visitor: V,
    ) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        self.deserialize_seq(visitor)
    }

    fn deserialize_identifier<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        visitor.visit_string(self.cord.color)
    }

    fn deserialize_ignored_any<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        visitor.visit_unit()
    }

    fn deserialize_bytes<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        // Not implemented really
        visitor.visit_bytes(&[])
    }

    fn deserialize_byte_buf<V>(self, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        visitor.visit_byte_buf(vec![])
    }

    fn deserialize_enum<V>(
        self,
        _name: &'static str,
        _variants: &'static [&'static str],
        visitor: V,
    ) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        // Enums?
        // Usually represented as map { Variant: Content } or just String "Variant"
        // If content is empty (Unit variant), maybe just string?

        if self.cord.subsidiaries.is_empty() {
            visitor.visit_enum(de::value::StringDeserializer::<Error>::new(self.cord.color))
        } else {
            // Variant struct/tuple
            visitor.visit_enum(CordEnumAccess { cord: self.cord })
        }
    }
}

struct CordMapAccess {
    iter: std::vec::IntoIter<Cord>,
    next_value: Option<Cord>,
}

impl CordMapAccess {
    fn new(subsidiaries: Vec<Cord>) -> Self {
        Self {
            iter: subsidiaries.into_iter(),
            next_value: None,
        }
    }
}

impl<'de> MapAccess<'de> for CordMapAccess {
    type Error = Error;

    fn next_key_seed<K>(&mut self, seed: K) -> Result<Option<K::Value>, Self::Error>
    where
        K: de::DeserializeSeed<'de>,
    {
        if let Some(cord) = self.iter.next() {
            // The "Key" is the color of the cord.
            // We must clone because we move cord into self.next_value
            let color = cord.color.clone();
            let key_deserializer: de::value::StringDeserializer<Error> =
                de::value::StringDeserializer::new(color);
            self.next_value = Some(cord);
            seed.deserialize(key_deserializer).map(Some)
        } else {
            Ok(None)
        }
    }

    fn next_value_seed<V>(&mut self, seed: V) -> Result<V::Value, Self::Error>
    where
        V: de::DeserializeSeed<'de>,
    {
        if let Some(cord) = self.next_value.take() {
            let deserializer = CordDeserializer { cord };
            seed.deserialize(deserializer)
        } else {
            Err(Error::Message("Value missing".to_string()))
        }
    }
}

struct CordSeqAccess {
    iter: std::vec::IntoIter<Cord>,
}

impl CordSeqAccess {
    fn new(subsidiaries: Vec<Cord>) -> Self {
        Self {
            iter: subsidiaries.into_iter(),
        }
    }
}

impl<'de> SeqAccess<'de> for CordSeqAccess {
    type Error = Error;

    fn next_element_seed<T>(&mut self, seed: T) -> Result<Option<T::Value>, Self::Error>
    where
        T: de::DeserializeSeed<'de>,
    {
        if let Some(cord) = self.iter.next() {
            let deserializer = CordDeserializer { cord };
            seed.deserialize(deserializer).map(Some)
        } else {
            Ok(None)
        }
    }
}

struct CordEnumAccess {
    cord: Cord,
}

impl<'de> de::EnumAccess<'de> for CordEnumAccess {
    type Error = Error;
    type Variant = CordVariantAccess;

    fn variant_seed<V>(self, seed: V) -> Result<(V::Value, Self::Variant), Self::Error>
    where
        V: de::DeserializeSeed<'de>,
    {
        let variant_deserializer: de::value::StringDeserializer<Error> =
            de::value::StringDeserializer::new(self.cord.color.clone());
        let val = seed.deserialize(variant_deserializer)?;
        Ok((val, CordVariantAccess { cord: self.cord }))
    }
}

struct CordVariantAccess {
    cord: Cord,
}

impl<'de> de::VariantAccess<'de> for CordVariantAccess {
    type Error = Error;

    fn unit_variant(self) -> Result<(), Self::Error> {
        Ok(())
    }

    fn newtype_variant_seed<T>(self, seed: T) -> Result<T::Value, Self::Error>
    where
        T: de::DeserializeSeed<'de>,
    {
        // The value is in the cord itself? Or the first subsidiary?
        // Newtype variant is like Wrapper(Content).
        // Our serializer: cord.color = Variant, content serialized inside.
        // If content is struct, subsidiaries. If content is primitive, clusters.
        let deserializer = CordDeserializer { cord: self.cord };
        seed.deserialize(deserializer)
    }

    fn tuple_variant<V>(self, _len: usize, visitor: V) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        de::Deserializer::deserialize_seq(CordDeserializer { cord: self.cord }, visitor)
    }

    fn struct_variant<V>(
        self,
        _fields: &'static [&'static str],
        visitor: V,
    ) -> Result<V::Value, Self::Error>
    where
        V: Visitor<'de>,
    {
        de::Deserializer::deserialize_map(CordDeserializer { cord: self.cord }, visitor)
    }
}
